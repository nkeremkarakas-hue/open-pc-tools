const { contextBridge, ipcRenderer } = require('electron');
contextBridge.exposeInMainWorld('pcTools', {
  listApps: () => ipcRenderer.invoke('apps:list'),
  addApp: (item) => ipcRenderer.invoke('apps:add', item),
  removeApp: (id) => ipcRenderer.invoke('apps:remove', id),
  launch: (executable, protocol) => ipcRenderer.invoke('apps:launch', executable, protocol),
  scan: (target) => ipcRenderer.invoke('security:scan', target),
  vaultStatus: () => ipcRenderer.invoke('vault:status'),
  listAccounts: () => ipcRenderer.invoke('vault:list'),
  saveAccount: (account) => ipcRenderer.invoke('vault:save', account),
  deleteAccount: (id) => ipcRenderer.invoke('vault:delete', id),
  openSteam: () => ipcRenderer.invoke('vault:open-steam'),
  listProviders: () => ipcRenderer.invoke('providers:list'),
  openProviderLogin: (id) => ipcRenderer.invoke('providers:login', id),
  steamApiStatus: () => ipcRenderer.invoke('steamapi:status'),
  saveSteamApi: (config) => ipcRenderer.invoke('steamapi:save', config),
  loadSteamStats: () => ipcRenderer.invoke('steamapi:stats'),
  donationConfig: () => ipcRenderer.invoke('donation:config'),
  getProfile: () => ipcRenderer.invoke('profile:get'),
  saveProfile: (profile) => ipcRenderer.invoke('profile:save', profile),
  checkForUpdates: () => ipcRenderer.invoke('update:check'),
  updateState: () => ipcRenderer.invoke('update:state'),
  performanceProfiles: () => ipcRenderer.invoke('performance:profiles'),
  performanceRecommend: (system) => ipcRenderer.invoke('performance:recommend', system),
  searchTranslation: (gameName, source) => ipcRenderer.invoke('translation:search', gameName, source),
  listMusic: () => ipcRenderer.invoke('music:list'),
  pickMusic: () => ipcRenderer.invoke('music:pick'),
  removeMusic: (id) => ipcRenderer.invoke('music:remove', id),
  recordGame: (input) => ipcRenderer.invoke('games:record', input),
  gameRecords: () => ipcRenderer.invoke('games:records'),
  clearGameRecords: () => ipcRenderer.invoke('games:clear-records'),
  systemSnapshot: () => ipcRenderer.invoke('system:snapshot'),
  gamePrice: (appid) => ipcRenderer.invoke('game:price', appid),
  loadLocale: (locale) => ipcRenderer.invoke('locale:load', locale),
  systemInfo: () => ipcRenderer.invoke('system:info'),
  openExternal: (url) => ipcRenderer.invoke('shell:open', url)
});
